def requirement_text(p: dict) -> str:
    req = p["requirement"]
    lines = [f"ประเภทงาน: {KINDS.get(p['kind'], KINDS['research'])['label']}"]
    for key, label in REQ_LABELS.items():
        if (req.get(key) or "").strip():
            lines.append(f"{label}: {req[key].strip()}")
    return "\n".join(lines)


def plan_text(p: dict) -> str:
    plan = dict(p.get("plan") or {})
    for k in ("keywords_th", "keywords_en", "ch2_outline"):
        plan.pop(k, None)
    return (f"ชื่อเรื่อง: {p['title_th']}\nชื่อเรื่องภาษาอังกฤษ: {p['title_en']}\n"
            f"แผนของงาน (JSON): {json.dumps(plan, ensure_ascii=False)}")


def refs_text(papers: list[dict], detail: bool = True) -> str:
    out = []
    for r in papers:
        m, s = r["meta"], r["summary"]
        lang = "ไทย" if m.get("lang") == "th" else "ต่างประเทศ"
        line = f"[{r['rkey']}] ({lang}) {r['narr']} — {m.get('title', '')}"
        if detail:
            for label, key in (("วัตถุประสงค์", "objective"), ("กลุ่มตัวอย่าง", "sample"), ("วิธีวิจัย", "method"),
                               ("เครื่องมือ", "instruments"), ("ผลการวิจัย", "findings"), ("แนวคิดสำคัญ", "concepts")):
                if s.get(key):
                    line += f"\n    {label}: {s[key]}"
        out.append(line)
    return "\n".join(out)


